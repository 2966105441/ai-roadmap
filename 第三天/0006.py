#2.浮点数比较的坑
print(0.1 + 0.2 == 0.3)
#0.1 + 0.2 不等于 0.3？
# 0.1 + 0.2 不等于 0.3？
# 这不是 Python 的 bug，是所有计算机的通病——二进制存不了 0.1 和 0.2，加起来的精度差一点点。
# 所以：永远不要用 == 比较两个小数。正确做法是看差值够不够小：
# abs(a - b) < 0.000001
