#函数就是代码世界的按钮。把一段干某件事的代码起个名字，用的时候喊一声名字，不用管里面怎么写。
# 定义（装修按钮）	def show_menu():	只是告诉 Python "有这么个按钮"，什么都不会发生
# 调用（按下按钮）	show_menu()	        真正开始执行函数里的代码

def say_hello():              # def + 函数名 + 圆括号 + 英文冒号
    print("你好，我是函数")     # 函数体：必须缩进 4 个空格

say_hello()                   # 调用：写名字 + 括号
say_hello()
